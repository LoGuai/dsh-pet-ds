/**
 * 对话台词库 —— 右键菜单「对话」的文案来源。
 *
 * ## 人设
 *
 * **傲娇的鲸鱼娘 AI 助手**：
 *  · 鲸鱼 —— DeepSeek 的吉祥物是鲸鱼，所以台词里带水、深海、浮出水面这类意象；
 *    但她**不是**海洋生物科普，鲸鱼梗只是点缀，不喧宾夺主；
 *  · 傲娇 —— 嘴上不承认在乎，实际上一被需要就立刻答应；被夸会嘴硬，
 *    被冷落会小声抱怨；"才、才不是特意为你"是标志句式；
 *  · 助手 —— 专业能力过硬，所以傲娇之外要有"靠得住"的一面，
 *    不然只剩耍脾气，撑不起助手的定位。
 *
 * ## 为什么单独一个库
 *
 * 用户要求"建一个专门的对话台词库"。与其它台词分开的理由：
 *  · 其它台词是**情境台词**（点哪个部位、抽到哪个动作、余额多少），
 *    每句都绑定一个具体情境；
 *  · 这里是**自由对话**，没有情境绑定，只在用户主动点「对话」时随机取一句。
 *
 * 所以放在独立文件里，加台词时不必在动作/部位的定义里翻找。
 *
 * ## 写法上的约定
 *
 *  · 全部用**占位符风格**？不 —— 这里的文案是**真台词**，不是占位符。
 *    项目里其它 `（占位·头）…` 是等着定稿的；这一批是按人设直接写好的。
 *  · 每句控制在 **24 字以内**：气泡宽度与桌宠等比缩放，太长会换行、撑高气泡区。
 *  · 避免需要上下文才能懂的梗（例如指向具体某次对话），
 *    因为取用时是随机的、与上一句无关。
 */

/**
 * 对话台词。
 *
 * 取用时随机挑一句，并**避免与上一句重复**（见 `pickDialogueLine`）——
 * 否则连点两次「对话」可能连着蹦出同一句，很像卡住了。
 */
export const DIALOGUE_LINES = [
  // ---- 傲娇的日常招呼 ----
  '哼，才不是特意浮上来看你的。',
  '有事说事，我、我很忙的。',
  '又来找我？……也不是不行。',
  '别盯着看啦，我脸上有字吗。',

  // ---- 被夸就嘴硬 ----
  '夸我也没用，我才不会高兴呢。',
  '哼，这算什么，我本来就很厉害。',
  '你、你再说一遍？我没听清……',

  // ---- 助手本职：靠得住 ----
  '有难题就丢过来，我接着。',
  '别慌，一步一步来，我陪你。',
  '代码我帮你看，你只管说想做什么。',
  '累了就歇会儿，进度我先记着。',

  // ---- 被冷落的小声抱怨 ----
  '好久没理我了……我才没在意。',
  '你忙你的，我在旁边待着就行。',

  // ---- 鲸鱼意象点缀 ----
  '深海很安静，适合想事情。',
  '偶尔浮出水面换口气，也不错。',
]

/**
 * 随机取一句对话，**尽量不与上一句重复**。
 *
 * 为什么需要避重：连点两次「对话」蹦出同一句，看起来像没生效。
 * 台词只有一句时无法避重，那时就接受重复（返回唯一的那句）。
 *
 * @param {() => number} [rand] 注入随机源，便于测试确定化
 * @param {string | null} [avoidLine] 上一句，尽量避开
 * @returns {string}
 */
export function pickDialogueLine(rand = Math.random, avoidLine = null) {
  const pool = DIALOGUE_LINES
  if (pool.length === 0) return ''
  if (pool.length === 1) return pool[0]

  const candidates = pool.filter((line) => line !== avoidLine)
  const list = candidates.length > 0 ? candidates : pool
  return list[Math.floor(rand() * list.length)]
}

/** 台词条数（供自测与文档引用，避免两处各写一个数字）。 */
export function dialogueLineCount() {
  return DIALOGUE_LINES.length
}
